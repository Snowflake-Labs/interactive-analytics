WITH boundaries AS (
SELECT
  MAX(L_SHIPDATE) AS end_date,
  DATEADD(month, -3, MAX(L_SHIPDATE)) AS start_date
FROM LINEITEM
)
SELECT
  COUNT(*) as rowc,
  MAX(l.L_SHIPDATE) AS ship_date,
  o.O_ORDERSTATUS AS status,
  ROUND(SUM(l.L_EXTENDEDPRICE * (1 - l.L_DISCOUNT)), 2) AS total_amount
FROM LINEITEM l
JOIN ORDERS o ON o.O_ORDERKEY = l.L_ORDERKEY
JOIN CUSTOMER c ON c.C_CUSTKEY = o.O_CUSTKEY
JOIN NATION n ON n.N_NATIONKEY = c.C_NATIONKEY
JOIN "REGION" r ON r.R_REGIONKEY = n.N_REGIONKEY
CROSS JOIN boundaries
WHERE l.L_SHIPDATE BETWEEN boundaries.start_date AND boundaries.end_date
AND c.C_MKTSEGMENT = 'HOUSEHOLD' AND r.R_NAME = 'AMERICA'
GROUP BY l.L_SHIPDATE, o.O_ORDERSTATUS, c.C_MKTSEGMENT, r.R_NAME
ORDER BY SHIP_DATE, o.O_ORDERSTATUS;
